public class ModDemo {
    public static void main(String[] args) {
        int iresult, iren;
        double dresult, dren;

        iresult = 10 / 3;
        iren = 10 % 3;

        dresult = 10.0 / 3;
        dren = 10.0 % 3;

        System.out.println(iresult + " | " + iren);
        System.out.println(dresult + " | " + dren);
    }
}
